/** Структура одного расчёта в памяти Leo */
export interface LeoCalculation {
  date: string
  question: string
  assumptions: string
  result: string
  actual_outcome: string | null
}

export function buildLeoContext(context: {
  // Базовый финансовый контекст
  niche: string
  price?: number  // из strategy_summary, может быть undefined если не извлечён
  kill_switch_date: string
  kill_switch_days_remaining: number
  kill_switch_metric: string
  // Ресурсы
  hours_per_week?: number
  monthly_budget?: number
  // Метрики
  mrr?: number
  paying_clients?: number
  messages_sent?: number
  reply_rate?: number
  conversion_rate?: number
  churn_rate?: number
  // S5 calculator
  target_mrr?: number
  cac_scenario?: string
  // Память расчётов
  leo_calculations?: LeoCalculation[]
}): string {
  const {
    niche, price, kill_switch_date, kill_switch_days_remaining, kill_switch_metric,
    hours_per_week, monthly_budget,
    mrr, paying_clients, messages_sent, reply_rate, conversion_rate, churn_rate,
    target_mrr, cac_scenario,
    leo_calculations,
  } = context

  const lines: string[] = []

  lines.push('==========================================================')
  lines.push('КОНТЕКСТ ДЛЯ LEO')
  lines.push('==========================================================')
  lines.push('')
  lines.push(`Ниша: ${niche}`)
  if (price !== undefined && price > 0) {
    lines.push(`Текущая цена: $${price}`)
  } else {
    lines.push('Текущая цена: уточни у пользователя или из S3')
  }
  lines.push(`Kill Switch: ${kill_switch_date} (${kill_switch_days_remaining} дней)`)
  lines.push(`Метрика KS: ${kill_switch_metric}`)
  lines.push('')

  if (hours_per_week !== undefined || monthly_budget !== undefined) {
    lines.push('Ресурсы:')
    if (hours_per_week !== undefined) lines.push(`- Часов в неделю: ${hours_per_week}`)
    if (monthly_budget !== undefined) lines.push(`- Бюджет/мес: $${monthly_budget}`)
    lines.push('')
  }

  const hasMetrics = mrr !== undefined || paying_clients !== undefined ||
    messages_sent !== undefined || reply_rate !== undefined
  if (hasMetrics) {
    lines.push('Текущие метрики:')
    if (paying_clients !== undefined) lines.push(`- Платящих клиентов: ${paying_clients}`)
    if (mrr !== undefined) lines.push(`- MRR: $${mrr}`)
    if (messages_sent !== undefined) lines.push(`- Отправлено сообщений: ${messages_sent}`)
    if (reply_rate !== undefined) lines.push(`- Reply rate: ${(reply_rate * 100).toFixed(1)}%`)
    if (conversion_rate !== undefined) lines.push(`- Конверсия в клиента: ${(conversion_rate * 100).toFixed(1)}%`)
    if (churn_rate !== undefined) lines.push(`- Churn: ${(churn_rate * 100).toFixed(1)}%/мес`)
    lines.push('')
  }

  if (target_mrr || cac_scenario) {
    lines.push('Финансовая цель (S5):')
    if (target_mrr) lines.push(`- Целевой MRR: $${target_mrr}`)
    if (cac_scenario) lines.push(`- CAC сценарий: ${cac_scenario}`)
    lines.push('')
  }

  if (leo_calculations?.length) {
    lines.push('Память расчётов Leo (последние):')
    leo_calculations.slice(-5).forEach((calc, i) => {
      lines.push(`\nРасчёт ${i + 1} (${calc.date}):`)
      lines.push(`- Вопрос: ${calc.question}`)
      lines.push(`- Допущения: ${calc.assumptions}`)
      lines.push(`- Результат: ${calc.result}`)
      if (calc.actual_outcome) {
        lines.push(`- Фактический исход: ${calc.actual_outcome}`)
      }
    })
    lines.push('')
  }

  return lines.join('\n')
}
