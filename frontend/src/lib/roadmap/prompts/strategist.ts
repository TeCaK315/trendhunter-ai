export function buildMaxContext(context: {
  // Базовый контекст пользователя
  niche: string
  positioning_angle?: string
  channel?: string
  price?: string
  resource_profile?: string
  // Метрики
  messages_sent?: number
  replies_received?: number
  paying_clients?: number
  mrr?: number
  // Kill switch
  kill_switch_date: string
  kill_switch_metric: string
  day_number: number
  days_remaining: number
  // Память
  user_memory?: string
  // Краткое саммари стратегии
  strategy_summary?: string
  // Последние события
  recent_summary?: string
}): string {
  const {
    niche, positioning_angle, channel, price, resource_profile,
    messages_sent, replies_received, paying_clients, mrr,
    kill_switch_date, kill_switch_metric, day_number, days_remaining,
    user_memory, strategy_summary, recent_summary,
  } = context

  const lines: string[] = []

  lines.push('==========================================================')
  lines.push('КОНТЕКСТ ПОЛЬЗОВАТЕЛЯ')
  lines.push('==========================================================')
  lines.push('')
  lines.push(`Ниша: ${niche}`)
  if (positioning_angle) lines.push(`Угол позиционирования: ${positioning_angle}`)
  if (channel) lines.push(`Канал: ${channel}`)
  if (price) lines.push(`Цена: ${price}`)
  if (resource_profile) lines.push(`Ресурсный профиль: ${resource_profile}`)
  lines.push('')
  lines.push(`День Роадмапа: ${day_number} из 90`)
  lines.push(`Kill Switch: ${kill_switch_date} (${days_remaining} дней до дедлайна)`)
  lines.push(`Метрика: ${kill_switch_metric}`)
  lines.push('')

  if (messages_sent !== undefined || paying_clients !== undefined) {
    lines.push('Текущие метрики:')
    if (messages_sent !== undefined) lines.push(`- Отправлено сообщений: ${messages_sent}`)
    if (replies_received !== undefined) lines.push(`- Получено ответов: ${replies_received}`)
    if (paying_clients !== undefined) lines.push(`- Платящих клиентов: ${paying_clients}`)
    if (mrr !== undefined) lines.push(`- MRR: $${mrr}`)
    lines.push('')
  }

  if (strategy_summary) {
    lines.push('Стратегия (краткое):')
    lines.push(strategy_summary)
    lines.push('')
  }

  if (user_memory) {
    lines.push('Что я помню о тебе:')
    lines.push(user_memory)
    lines.push('')
  }

  if (recent_summary) {
    lines.push('Последние события:')
    lines.push(recent_summary)
    lines.push('')
  }

  return lines.join('\n')
}

